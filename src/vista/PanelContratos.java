    private void btnCrearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearActionPerformed
         try {
            String idCliente = txtIdCliente.getText().trim();
            TipoEspacio tipo = (TipoEspacio) comboTipo.getSelectedItem();
            LocalDate inicio = UtilDate.toLocalDate(txtFechaInicio.getText().trim());
            LocalDate fin = UtilDate.toLocalDate(txtFechaFin.getText().trim());

            Contrato contrato = controlador.crearContrato(idCliente, tipo, inicio, fin);

            JOptionPane.showMessageDialog(this,
                    "Contrato #" + contrato.getNumeroContrato() + " creado en estado Pendiente.\n"
                    + "Espacio asignado: #" + contrato.getEspacio().getNumero() + "\n"
                    + "Total: " + contrato.getTotal());
            limpiarFormulario();
            refrescarTabla(controlador.listarContratos());
        } catch (DateTimeParseException ex) {
            JOptionPane.showMessageDialog(this, "Las fechas deben tener el formato dd/MM/yyyy.",
                    "Error", JOptionPane.ERROR_MESSAGE);
        } catch (IllegalArgumentException | StoreBoxException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCrearActionPerformed

    private void btnAgregarServicioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarServicioActionPerformed
        try {
            if (numeroseleccionado < 0) {
                JOptionPane.showMessageDialog(this, "Seleccione un contrato de la tabla.",
                        "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            if (txtCodigoServicio.getText().trim().isBlank()) {
                JOptionPane.showMessageDialog(this, "Escriba el código del servicio a agregar.",
                        "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            int codigoServicio = Integer.parseInt(txtCodigoServicio.getText().trim());
            controlador.agregarServicioAContrato(numeroseleccionado, codigoServicio);

            JOptionPane.showMessageDialog(this, "Servicio agregado al contrato #" + numeroseleccionado + ".");
            refrescarTabla(controlador.listarContratos());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "El código de servicio debe ser numérico.",
                    "Error", JOptionPane.ERROR_MESSAGE);
        } catch (StoreBoxException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAgregarServicioActionPerformed

