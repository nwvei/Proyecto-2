    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        Integer numero = null;
        if (!txtBuscarNumero.getText().trim().isBlank()) {
            try {
                numero = Integer.parseInt(txtBuscarNumero.getText().trim());
            } catch (NumberFormatException ex) {
                JOptionPane.showMessageDialog(this, "El número de contrato debe ser numérico.",
                        "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }
        String cliente = txtBuscarCliente.getText().trim();
        EstadoContrato estado = (EstadoContrato) comboBuscarEstado.getSelectedItem();

        List<Contrato> resultado = controlador.buscarContratos(
                numero, cliente.isBlank() ? null : cliente, null, null, estado);
        refrescarTabla(resultado);
    }//GEN-LAST:event_btnBuscarActionPerformed

