    private void cambiarEstado(String accion) {
        try {
            if (numeroseleccionado < 0) {
                JOptionPane.showMessageDialog(this, "Seleccione un contrato de la tabla.",
                        "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            switch (accion) {
                case "activar" -> controlador.activarContrato(numeroseleccionado);
                case "finalizar" -> controlador.finalizarContrato(numeroseleccionado);
                case "cancelar" -> controlador.cancelarContrato(numeroseleccionado);
                default -> throw new IllegalStateException("Acción no reconocida: " + accion);
            }
            JOptionPane.showMessageDialog(this, "Operación realizada correctamente sobre el contrato #"
                    + numeroseleccionado + ".");
            refrescarTabla(controlador.listarContratos());
        } catch (StoreBoxException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    
    
     private void limpiarFormulario() {
        txtIdCliente.setText("");
        comboTipo.setSelectedIndex(0);
        txtFechaInicio.setText("");
        txtFechaFin.setText("");
        txtCodigoServicio.setText("");
        numeroseleccionado = -1;
        tablaContratos.clearSelection();
    }
     
    private void refrescarTabla(List<Contrato> contratos) {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tablaContratos.getModel();
        modelo.setRowCount(0);
        for (Contrato c : contratos) {
            modelo.addRow(new Object[]{
                c.getNumeroContrato(),
                c.getCliente() != null ? c.getCliente().getNombreCompleto() : "N/A",
                c.getEspacio() != null ? c.getEspacio().getNumero() : "N/A",
                UtilDate.toString(c.getFechaInicio()),
                UtilDate.toString(c.getFechaFin()),
                c.getEstado(),
                c.getSubtotal(),
                c.getImpuesto(),
                c.getTotal()
            });
        }
    }
